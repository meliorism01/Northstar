export function buildInitialOrders(customers = INITIAL_CUSTOMERS, rules = INITIAL_AUTOMATION_RULES) {
  const customerMap = Object.fromEntries(customers.map((c) => [c.id, c]));
  return RAW_ORDERS.map((order) => {
    const customer = customerMap[order.customerId];
    const risk = evaluateOrderRisk(order, customer, rules);
    return {
      ...order,
      ...risk,
      history: [
        {
          timestamp: order.date,
          type: 'Order Ingested',
          detail: `Order ${order.id} received from ${order.store} (${order.paymentMode}, ₹${order.orderValue.toLocaleString('en-IN')})`,
        },
        ...(order.rescued
          ? [
              {
                timestamp: order.date,
                type: 'Intervention Completed',
                detail: `Customer verified via WhatsApp workflow; cleared for dispatch.`,
              },
            ]
          : []),
      ],
    };
  });
}

